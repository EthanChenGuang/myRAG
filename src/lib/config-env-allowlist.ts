export const MAX_CONFIG_VALUE_LENGTH = 20000;

export function isWritableEnvName(name: string): boolean {
  return CONFIG_WRITABLE_ENV_NAMES.has(name) && !isSecretEnvName(name);
}

export function isReadableEnvEntry(name: string, value: string): boolean {
  return isWritableEnvName(name) && !URL_WITH_CREDENTIALS.test(value);
}
