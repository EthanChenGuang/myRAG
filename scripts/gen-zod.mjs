import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { jsonSchemaToZod } from 'json-schema-to-zod';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');

function parseArgs(argv) {
  const args = {
    schemasDir: path.join(ROOT, 'rag-sidecar', 'schemas'),
    out: path.join(ROOT, 'src', 'lib', 'rag-eval', 'contracts.generated.ts'),
    registry: path.join(ROOT, 'config', 'rag', 'language-packs.json'),
    textsOut: path.join(ROOT, 'src', 'lib', 'rag', 'lang', 'texts.generated.ts'),
  };
  let outGiven = false;
  let textsOutGiven = false;
  for (let i = 0; i < argv.length; i += 1) {
    if (argv[i] === '--schemas-dir') args.schemasDir = path.resolve(argv[++i]);
    else if (argv[i] === '--out') {
      args.out = path.resolve(argv[++i]);
      outGiven = true;
    } else if (argv[i] === '--registry') args.registry = path.resolve(argv[++i]);
    else if (argv[i] === '--texts-out') {
      args.textsOut = path.resolve(argv[++i]);
      textsOutGiven = true;
    }
  }
  // A run that redirects the contracts elsewhere writes no texts module unless it names one.
  if (outGiven && !textsOutGiven) args.textsOut = null;
  return args;
}

function writeAtomic(out, text) {
  fs.mkdirSync(path.dirname(out), { recursive: true });
  const tmp = `${out}.${process.pid}.tmp`;
  try {
    fs.writeFileSync(tmp, text);
    fs.renameSync(tmp, out);
  } catch (error) {
    fs.rmSync(tmp, { force: true });
    throw error;
  }
}

function sortedGroup(group, code, name) {
  if (!group || typeof group !== 'object' || Array.isArray(group)) fail(`${code}: texts.${name} must be an object`);
  return Object.fromEntries(
    Object.keys(group)
      .sort()
      .map((key) => {
        const value = group[key];
        if (value !== null && typeof value !== 'string') fail(`${code}: texts.${name}.${key} must be a string or null`);
        return [key, value];
      }),
  );
}

// Phase 5.2 D-12: the notices and labels of every pack for the browser. Instructions are prompt text and are never shipped.
function writeFixedTexts(registryPath, out) {
  const registry = JSON.parse(fs.readFileSync(registryPath, 'utf8'));
  if (!Array.isArray(registry.packs) || registry.packs.length === 0) fail(`${registryPath} has no packs`);
  const texts = {};
  for (const pack of registry.packs) {
    const code = pack.code;
    if (typeof code !== 'string' || code === '') fail(`${registryPath}: a pack has no code`);
    texts[code] = { labels: sortedGroup(pack.texts?.labels, code, 'labels'), notices: sortedGroup(pack.texts?.notices, code, 'notices') };
  }
  const text = [
    '// GENERATED by scripts/gen-zod.mjs from config/rag/language-packs.json - do not edit',
    '// Phase 5.2 D-12: the notices and labels groups only, for the browser.',
    '',
    'export interface FixedClientTexts {',
    '  readonly notices: Readonly<Record<string, string | null>>;',
    '  readonly labels: Readonly<Record<string, string | null>>;',
    '}',
    '',
    `export const FIXED_TEXTS: Readonly<Record<string, FixedClientTexts>> = ${JSON.stringify(texts, null, 2)};`,
    '',
  ].join('\n');
  writeAtomic(out, text);
  console.log(`[gen-zod] wrote ${path.relative(ROOT, out)} (${registry.packs.length} languages)`);
}

function fail(message) {
  throw new Error(message);
}

function inline(node, defs, stack = []) {
  if (Array.isArray(node)) return node.map((item) => inline(item, defs, stack));
  if (node && typeof node === 'object') {
    if (typeof node.$ref === 'string') {
      const name = node.$ref.replace('#/$defs/', '');
      if (stack.includes(name)) fail(`cyclic $ref ${[...stack, name].join(' -> ')}`);
      if (!(name in defs)) fail(`unresolved $ref ${node.$ref}`);
      return inline(defs[name], defs, [...stack, name]);
    }
    const out = {};
    for (const [key, value] of Object.entries(node)) {
      if (key !== '$defs') out[key] = inline(value, defs, stack);
    }
    if (out.oneOf && out.discriminator) {
      out.anyOf = out.oneOf;
      delete out.oneOf;
      delete out.discriminator;
    }
    return out;
  }
  return node;
}

function main() {
  const { schemasDir, out, registry, textsOut } = parseArgs(process.argv.slice(2));
  const files = fs
    .readdirSync(schemasDir)
    .filter((file) => file.endsWith('.schema.json'))
    .sort();
  if (files.length === 0) fail(`no *.schema.json files found in ${schemasDir}`);

  const blocks = [];
  const titles = new Map();
  for (const file of files) {
    const root = JSON.parse(fs.readFileSync(path.join(schemasDir, file), 'utf8'));
    const model = root.title;
    if (typeof model !== 'string' || model === '') fail(`${file} has no top-level title`);
    if (titles.has(model)) fail(`duplicate model title ${model} in ${titles.get(model)} and ${file}`);
    titles.set(model, file);
    const code = jsonSchemaToZod(inline(root, root.$defs ?? {}), {
      name: `${model}Schema`,
      module: 'esm',
      type: model,
    });
    blocks.push(
      code
        .split('\n')
        .filter((line) => !line.startsWith('import '))
        .join('\n')
        .trim(),
    );
  }

  const body = blocks
    .join('\n\n')
    .replace(/\bz\.any\(\)/g, 'z.unknown()');
  const text = [
    '// GENERATED by scripts/gen-zod.mjs from rag-sidecar/schemas - do not edit',
    "import { z } from 'zod/v3';",
    '',
    body,
    '',
  ].join('\n');

  writeAtomic(out, text);
  console.log(`[gen-zod] wrote ${path.relative(ROOT, out)} (${files.length} schemas)`);
  if (textsOut) writeFixedTexts(registry, textsOut);
}

try {
  main();
} catch (error) {
  console.error(`[gen-zod] ${error instanceof Error ? error.message : String(error)}`);
  process.exit(1);
}
